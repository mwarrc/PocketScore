package com.mwarrc.pocketscore.data.local.room.entity

import androidx.room.ColumnInfo
import androidx.room.Entity
import androidx.room.Index
import androidx.room.PrimaryKey

/**
 * Persisted match header.
 *
 * Holds everything about a game that is not per-player or per-event: lifecycle
 * flags, timestamps and table state. Players and events are separate tables that
 * reference [id] and are deleted with it via `ON DELETE CASCADE`.
 *
 * Indexes mirror the app's hot queries: the Records list sorts by [lastUpdate]
 * and filters archives, while the active-game lookup filters on
 * `isArchived + isGameActive + lastUpdate`.
 *
 * @property id Stable identifier generated by the domain layer. Also used when
 *   merging imports, so the same game imported twice is not duplicated.
 * @property isGameActive `true` while the match is the one currently in play.
 * @property isPaused `true` for a suspended match that can be resumed later.
 * @property startTime Epoch millis when the match began.
 * @property endTime Epoch millis when the match ended, or `null` while ongoing.
 * @property lastUpdate Epoch millis of the most recent change; drives ordering.
 * @property currentPlayerId ID of the player whose turn it is, or `null`.
 * @property canUndo Whether the last action can still be undone.
 * @property isFinalized `true` once results are locked and the game was counted.
 * @property ballsOnTable Pool-ball numbers not yet pocketed (1..15).
 * @property deviceInfo Name/model of the device that created the record; used to
 *   attribute imported games.
 * @property isArchived `true` when the user moved the record to the Archive tab.
 *   Finished games are *not* archived automatically.
 * @property syncStatus Reserved for future multi-device sync; `0` means local.
 */
@Entity(
    tableName = "games",
    indices = [
        Index(value = ["lastUpdate"], name = "index_games_lastUpdate"),
        Index(value = ["endTime"], name = "index_games_endTime"),
        Index(value = ["isArchived"], name = "index_games_isArchived"),
        Index(value = ["startTime"], name = "index_games_startTime"),
        Index(value = ["isArchived", "isGameActive", "lastUpdate"], name = "index_games_active_lookup")
    ]
)
data class GameEntity(
    @PrimaryKey
    @ColumnInfo(name = "id")
    val id: String,

    @ColumnInfo(name = "isGameActive")
    val isGameActive: Boolean = false,

    @ColumnInfo(name = "isPaused", defaultValue = "0")
    val isPaused: Boolean = false,

    @ColumnInfo(name = "startTime")
    val startTime: Long,

    @ColumnInfo(name = "endTime")
    val endTime: Long? = null,

    @ColumnInfo(name = "lastUpdate")
    val lastUpdate: Long,

    @ColumnInfo(name = "currentPlayerId")
    val currentPlayerId: String? = null,

    @ColumnInfo(name = "canUndo")
    val canUndo: Boolean = false,

    @ColumnInfo(name = "isFinalized")
    val isFinalized: Boolean = false,

    @ColumnInfo(name = "ballsOnTable")
    val ballsOnTable: Set<Int> = (1..15).toSet(),

    @ColumnInfo(name = "deviceInfo")
    val deviceInfo: String? = null,

    @ColumnInfo(name = "isArchived")
    val isArchived: Boolean = false,

    @ColumnInfo(name = "syncStatus")
    val syncStatus: Int = 0
)
